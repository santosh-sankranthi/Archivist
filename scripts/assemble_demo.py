#!/usr/bin/env python3
"""Assemble the demo video: burn captions from the take timeline, export MP4.

Usage:

    .venv/bin/python scripts/assemble_demo.py \
        --raw docs/demo/.raw/archivist-demo-raw.webm \
        --timeline docs/demo/.raw/archivist-demo-timeline.json \
        --out docs/demo/archivist-demo.mp4

The recorder (``scripts/record_demo.py``) logs event timestamps relative to
its take start; the video runs in real time, so caption times are the event
times scaled by the measured ratio (video duration / take wall span) — a
guard against the rare case where Playwright's clock drifts from the wall.

Captions are burned with libass (fade in/out, mono, warm grey) and a copy
is written as .srt next to the output. The encode is H.264 CRF 21, 25 fps,
faststart — the format GitHub plays inline.
"""

