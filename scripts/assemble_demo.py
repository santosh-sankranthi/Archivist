def ffprobe_duration(path: Path) -> float:
    out = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=nw=1:nk=1",
            str(path),
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    return float(out)


def ass_ts(t: float) -> str:
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def srt_ts(t: float) -> str:
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = int(t % 60)
    ms = round((t - int(t)) * 1000) % 1000
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def build_captions(
    events: dict[str, float], scale: float
) -> list[tuple[float, float, str, tuple[int, int] | None]]:
    entries: list[tuple[float, float, str, tuple[int, int] | None]] = []
    prev_end = 0.0
    for index, (anchor, offset, dur, text) in enumerate(CAPTIONS):
        if anchor not in events:
            print(f"  warn: no event {anchor!r} — caption skipped: {text[:40]}…")
            continue
        start = max(0.35, events[anchor] * scale + offset)
        start = max(start, prev_end + 0.3)
        end = start + dur
        if end - start < 1.2:
            print(f"  warn: caption squeezed ({end - start:.1f}s): {text[:40]}…")
            continue
        entries.append((start, end, text, POS_OVERRIDES.get(index)))
        prev_end = end
    return entries


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--raw",
        default=None,
        help="default: the raw path recorded in the take timeline",
    )
    ap.add_argument("--timeline", default="docs/demo/.raw/archivist-demo-timeline.json")
    ap.add_argument("--out", default="docs/demo/archivist-demo.mp4")
    ap.add_argument("--srt", default=None, help="default: <out without suffix>.srt")
    ap.add_argument("--crf", type=int, default=21)
    args = ap.parse_args()

    repo_root = Path(__file__).resolve().parents[1]
    timeline_path = (repo_root / args.timeline).resolve()
    data = json.loads(timeline_path.read_text(encoding="utf-8"))
    if args.raw:
        raw = (repo_root / args.raw).resolve()
    elif data.get("raw"):
        raw = Path(data["raw"])
    else:
        raw = (repo_root / "docs/demo/.raw/archivist-demo-raw.webm").resolve()
    out = (repo_root / args.out).resolve()
    srt = (repo_root / (args.srt or args.out.rsplit(".", 1)[0] + ".srt")).resolve()

    if not raw.is_file():
        raise SystemExit(f"raw recording missing: {raw} (run scripts/record_demo.py)")
    events = {}
    for event in data["events"]:
        events.setdefault(event["name"], event["t"])

    duration = ffprobe_duration(raw)
    scale = duration / data["close"] if data["close"] else 1.0
    print(
        f"take wall: {data['close']:.1f}s · video: {duration:.1f}s · scale: {scale:.4f}"
    )
    if not 0.9 <= scale <= 1.15:
        print(
            "  warn: video/wall mismatch is large — check caption sync before shipping"
        )

    captions = build_captions(events, scale)
    print(f"captions: {len(captions)}")
    for start, end, text, _pos in captions:
        print(f"  {ass_ts(start)} → {ass_ts(end)}  {text[:64]}")

    ass_lines = [ASS_HEADER]
    for start, end, text, pos in captions:
        override = "\\fad(160,160)"
        if pos is not None:
            override += f"\\an2\\pos({pos[0]},{pos[1]})"
        ass_lines.append(
            f"Dialogue: 0,{ass_ts(start)},{ass_ts(end)},Cap,,0,0,0,,{{{override}}}{text}\n"
        )
    ass_path = Path(tempfile.mkstemp(prefix="archivist-captions-", suffix=".ass")[1])
    ass_path.write_text("".join(ass_lines), encoding="utf-8")

    srt_lines = []
    for index, (start, end, text, _pos) in enumerate(captions, start=1):
        srt_lines.append(f"{index}\n{srt_ts(start)} --> {srt_ts(end)}\n{text}\n\n")
    srt.write_text("".join(srt_lines), encoding="utf-8")

    vf = (
        f"fps=25,subtitles=filename='{ass_path}',"
        f"fade=t=in:st=0:d=0.7,fade=t=out:st={max(duration - 0.7, 0.1):.2f}:d=0.7"
    )
    cmd = [
        "ffmpeg",
        "-y",
        "-loglevel",
        "error",
        "-stats",
        "-i",
        str(raw),
        "-vf",
        vf,
        "-c:v",
        "libx264",
        "-crf",
        str(args.crf),
        "-preset",
        "medium",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        "-an",
        str(out),
    ]
    print("encoding…")
    subprocess.run(cmd, check=True)

    final = ffprobe_duration(out)
    size_mb = out.stat().st_size / (1024 * 1024)
    print(f"done: {out}")
    print(f"  duration {final:.1f}s · size {size_mb:.1f} MB · srt {srt.name}")
    if size_mb > 95:
        print("  warn: over 95 MB — raise --crf and re-encode")
        return 4
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
